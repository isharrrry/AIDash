/**
 * 任务描述与内嵌图片的共享上限。
 *
 * 为什么需要共享：前端要在“插入图片”时提前拦住超限内容，服务端 zod 也要拒绝同样的
 * 上限；两边各写一个数字，迟早会出现“前端让存、后端 422”或反过来的割裂。
 *
 * 为什么不是 64 KB：Base64 大约把二进制放大 4/3，一张 1400px 截图很容易到几百 KB。
 * 64 KB 连一张正常截图都放不下，用户会以为是编辑器坏了。
 */
export const MAX_TASK_DESCRIPTION_CHARS = 2_000_000;

/**
 * 单张图片转成 Markdown data URL 后的字符上限。
 *
 * 单图过大时优先让前端降采样/降质量，而不是无限放宽描述上限：
 * SQLite 的 TEXT 能存，但备份、任务详情响应和浏览器内存都会跟着变大。
 */
export const MAX_EMBEDDED_IMAGE_CHARS = 700_000;

/** 粘贴图片降采样后的最长边（像素）。超过这个尺寸对截图阅读没有额外收益。 */
export const TASK_IMAGE_MAX_EDGE = 1440;

/**
 * 主通道记忆的字符上限。
 *
 * 为什么比任务描述小得多：记忆会在每次会话开场被 agent 读取，属于“长期上下文的固定成本”。
 * 2,000,000 字符的任务描述是一次性正文，而 64,000 字符的记忆已经约等于 16k token；
 * 超过这个量通常说明把日志/流水账也写进来了，应当清理而不是继续放宽。
 */
export const MAX_MEMORY_CHARS = 64_000;

/** 单次追加的行数上限：一次调用写几百行，说明调用方把它当批量导入而不是记忆追加。 */
export const MAX_MEMORY_APPEND_LINES = 50;

/** 单行记忆的字符上限：一行应该是一条可检索的约束，不是一整篇文档。 */
export const MAX_MEMORY_LINE_CHARS = 2_000;
