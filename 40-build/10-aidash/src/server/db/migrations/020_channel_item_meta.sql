-- 020：事项页的人工属性。
--
-- 为什么需要这一列：
--   “事项”页把每条子通道当作一件事来管理，用户要在左栏维护负责人、优先级、
--   阶段、分组、参与人、标签、迭代、产品、大类、备注。这些字段既不属于任务
--   （一个事项下有多个任务，且任务会结束），也不属于通道自身（status 只表达
--   是否归档）。单独存一份 JSON，语义最接近“这件事的档案”。
--
-- 为什么用 JSON 而不是十个列：
--   这些字段是展示/筛选用的用户标签，不参与 SQL 关联或唯一性约束；字段还会
--   继续长，每加一个都写迁移不划算。数据量是“通道数”级别（几十到几百条），
--   前端一次拉回后本地筛选完全够用。
--
-- 为什么允许为空：
--   迁移前的通道没有事项属性；空值表示“未维护”，页面显示“未设置”，
--   不回填任何假数据（例如不要把空优先级显示成 P2）。
ALTER TABLE channel ADD COLUMN meta_json TEXT;
